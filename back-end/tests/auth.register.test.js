// Tests for POST /auth/register.
// Run with: npm test (from the back-end folder). Uses the ecommerce_test
// database (see .env.test), so real data is never touched.
//
// How these tests work:
//   - `describe(name, fn)` groups related tests under a heading.
//   - `test(name, fn)` is one test: it does something, then checks the result.
//   - `assert.*` functions do the checking. If an assertion fails, the test
//     fails and the output shows what was expected and what actually happened.
//   - Each test sends real HTTP requests to the app using supertest, and
//     reads the real test database to check what changed. Nothing is faked.

// node:test is Node's built-in test runner.
//   beforeEach: runs a function before every test
//   after:      runs a function once, after all the tests
import { describe, test, beforeEach, after } from 'node:test';
// assert/strict provides the checks, e.g. assert.equal(actual, expected).
// "strict" means values must match exactly: 1 and '1' are NOT equal.
import assert from 'node:assert/strict';
// supertest sends HTTP requests straight to the app, without starting a server.
import request from 'supertest';
// bcrypt is used to check the stored password hash really matches the password.
import bcrypt from 'bcrypt';

import app from '../app.js';
// pool: the database connection pool, used to read what was actually saved.
import pool from '../db/index.js';
// resetTables: empties every table (see tests/helpers.js).
import { resetTables } from './helpers.js';

// A valid registration. Tests copy it and change one field at a time, using
// the "spread" syntax: `{ ...validUser, email: 'x' }` means "a copy of
// validUser, but with email set to 'x'".
const validUser = {
  first_name: 'Ada',
  last_name: 'Lovelace',
  email: 'ada@example.com',
  password: 'correct-horse-battery',
};

// Sends POST /auth/register with the given JSON body, and returns the
// response (once awaited). Saves repeating this line in every test.
const register = (body) => request(app).post('/auth/register').send(body);

// Counts every customer in the database.
// `::int` converts PostgreSQL's count (which pg returns as a string) into an
// integer, so it comes back as a JavaScript number.
const countCustomers = async () => {
  const result = await pool.query('SELECT count(*)::int AS count FROM customers');
  return result.rows[0].count;
};

describe('POST /auth/register', () => {
  // Start every test with empty tables, so tests can't affect each other.
  beforeEach(resetTables);

  // Close the database connections once all tests finish, or Node won't exit.
  after(() => pool.end());

  describe('with valid details', () => {
    test('returns 201 with the new customer', async () => {
      const res = await register(validUser);

      // `res.status` is the HTTP status code; `res.body` is the parsed JSON body.
      assert.equal(res.status, 201);
      // The id is generated by the database, so just check it's a number.
      assert.equal(typeof res.body.id, 'number');
      assert.equal(res.body.first_name, 'Ada');
      assert.equal(res.body.last_name, 'Lovelace');
      assert.equal(res.body.email, 'ada@example.com');
    });

    test('saves the customer to the database', async () => {
      const res = await register(validUser);

      // Read the database directly to prove the customer was really saved,
      // not just echoed back in the response.
      const result = await pool.query('SELECT email FROM customers WHERE id = $1', [res.body.id]);
      assert.equal(result.rows[0].email, 'ada@example.com');
    });

    test('never returns the password or its hash', async () => {
      const res = await register(validUser);

      // Check registration succeeded first, otherwise an error response
      // (which has no password in it either) would pass this test.
      assert.equal(res.status, 201);
      assert.equal(res.body.password, undefined);
      assert.equal(res.body.password_hash, undefined);
    });

    test('stores a bcrypt hash, not the plain-text password', async () => {
      await register(validUser);

      const result = await pool.query('SELECT password_hash FROM customers');
      // Destructuring: pull password_hash out of the first row.
      const { password_hash } = result.rows[0];
      // The stored value must not be the password itself...
      assert.notEqual(password_hash, 'correct-horse-battery');
      // ...but bcrypt must confirm it's a valid hash of that password.
      assert.equal(await bcrypt.compare('correct-horse-battery', password_hash), true);
    });

    test('stores the email trimmed and lower-cased', async () => {
      const res = await register({ ...validUser, email: '  Ada@Example.COM ' });

      assert.equal(res.status, 201);
      assert.equal(res.body.email, 'ada@example.com');
    });

    // Boundary values: the shortest and longest passwords that should be allowed.
    // Bugs often hide at the edges (e.g. writing < where <= was meant), so
    // test exactly at the limits. 'a'.repeat(8) makes 'aaaaaaaa'.
    // `for...of` loops over the array; `[name, password]` unpacks each pair,
    // creating one test per pair.
    for (const [name, password] of [
      ['an 8-character password (the minimum)', 'a'.repeat(8)],
      ['a 72-character password (the maximum bcrypt supports)', 'a'.repeat(72)],
    ]) {
      // Backticks make a template literal: ${name} inserts the description.
      test(`accepts ${name}`, async () => {
        // `{ ...validUser, password }` is shorthand for `password: password`.
        const res = await register({ ...validUser, password });

        assert.equal(res.status, 201);
      });
    }
  });

  describe('when the customer already exists', () => {
    test('returns 409 if the email is already registered', async () => {
      await register(validUser);

      const res = await register({ ...validUser, first_name: 'Someone else' });

      assert.equal(res.status, 409);
      // `typeof x` gives the type's name, so this checks an error message was sent.
      assert.equal(typeof res.body.error, 'string');
      // Still only one customer: the duplicate wasn't saved.
      assert.equal(await countCustomers(), 1);
    });

    test('returns 409 if the email differs only by letter case', async () => {
      await register(validUser);

      const res = await register({ ...validUser, email: 'ADA@example.com' });

      assert.equal(res.status, 409);
      assert.equal(await countCustomers(), 1);
    });

    test('returns 409 for one of two simultaneous registrations with the same email', async () => {
      // Promise.all() starts both requests at the same time and waits for both
      // to finish, simulating two people registering the same email at once.
      // It returns an array of the two responses.
      const responses = await Promise.all([register(validUser), register(validUser)]);

      // .map() turns each response into its status code, e.g. [409, 201].
      // We don't know which request "wins", so .sort() puts them in a fixed
      // order ([201, 409]) before comparing.
      const statuses = responses.map((res) => res.status).sort();
      // deepEqual compares the arrays' contents, not just whether they're the same object.
      assert.deepEqual(statuses, [201, 409]);
      assert.equal(await countCustomers(), 1);
    });
  });

  describe('with invalid details', () => {
    // A "table-driven" test: each entry is [description, request body], one
    // way a registration can be invalid. The loop below turns each entry into
    // its own test. All should be rejected with 400 and must not create a customer.
    // Setting a field to `undefined` leaves it out of the JSON body entirely.
    const invalidCases = [
      ['email is missing', { ...validUser, email: undefined }],
      ['email is empty', { ...validUser, email: '' }],
      ['email has no @', { ...validUser, email: 'ada.example.com' }],
      ['email has no domain', { ...validUser, email: 'ada@' }],
      ['email is longer than 255 characters', { ...validUser, email: `${'a'.repeat(250)}@example.com` }],
      ['password is missing', { ...validUser, password: undefined }],
      ['password is shorter than 8 characters', { ...validUser, password: 'a'.repeat(7) }],
      ['password is longer than 72 bytes', { ...validUser, password: 'a'.repeat(73) }],
      // "é" is 2 bytes in UTF-8, so 37 of them is 74 bytes despite being 37 characters.
      ['password is under 72 characters but over 72 bytes', { ...validUser, password: 'é'.repeat(37) }],
      ['password is not a string', { ...validUser, password: 12345678 }],
      ['first_name is missing', { ...validUser, first_name: undefined }],
      ['first_name is only spaces', { ...validUser, first_name: '   ' }],
      ['first_name is longer than 100 characters', { ...validUser, first_name: 'a'.repeat(101) }],
      ['last_name is missing', { ...validUser, last_name: undefined }],
      ['last_name is longer than 100 characters', { ...validUser, last_name: 'a'.repeat(101) }],
    ];

    for (const [name, body] of invalidCases) {
      test(`returns 400 when ${name}`, async () => {
        const res = await register(body);

        assert.equal(res.status, 400);
        assert.equal(typeof res.body.error, 'string');
        assert.equal(await countCustomers(), 0);
      });
    }

    test('returns 400 when no body is sent', async () => {
      // No .send(), so the request has no body at all.
      const res = await request(app).post('/auth/register');

      assert.equal(res.status, 400);
      assert.equal(typeof res.body.error, 'string');
    });

    test('returns 400 when the body is not valid JSON', async () => {
      // .set() adds a request header. Content-Type: application/json claims
      // the body is JSON, but '{ not json' is broken JSON, so express.json()
      // fails to parse it and app.js's error handler should reply 400.
      const res = await request(app)
        .post('/auth/register')
        .set('Content-Type', 'application/json')
        .send('{ not json');

      assert.equal(res.status, 400);
      assert.equal(typeof res.body.error, 'string');
    });
  });
});
